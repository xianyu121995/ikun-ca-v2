import { readFileSync, writeFileSync } from "node:fs";
const names=["login.html","account.html","users.html","password.html","auth.css","auth.js"];
const assets=Object.fromEntries(names.map(name=>[name,readFileSync(new URL(`../static/${name}`,import.meta.url),"utf8")]));
writeFileSync(new URL("../src/ui.ts",import.meta.url),`// Generated by scripts/generate-ui.mjs from static/. Do not hand-edit.\nexport const assets: Record<string,string> = ${JSON.stringify(assets,null,2)};\n`);
