const ten='test-next2';
for(const [length,allowed] of [[9,false],[10,true],[128,true],[129,false]])
 test(`password10 ASCII ${length} ${allowed?'accepted':'rejected'}`,()=>{
  const value='x'.repeat(length);
  if(allowed)assert.equal(validate(value),value);else assert.throws(()=>validate(value),e=>e.status===422&&e.message.includes('10–128'));
 });
